// Русские формы слов при числах и короткие фразы для ребёнка.

/** plural(5, 'пример', 'примера', 'примеров') → 'примеров' */
export function plural(n, one, few, many) {
  const a = Math.abs(n);
  const n10 = a % 10;
  const n100 = a % 100;
  if (n10 === 1 && n100 !== 11) return one;
  if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return few;
  return many;
}

export const withWord = (n, one, few, many) => `${n} ${plural(n, one, few, many)}`;

